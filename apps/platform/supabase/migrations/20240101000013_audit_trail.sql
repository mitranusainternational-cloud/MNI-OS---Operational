-- Tujuan: data dapat dipertanggungjawabkan. Setiap tambah, ubah, dan hapus pada tabel data tercatat OTOMATIS oleh
-- database (siapa, kapan, nilai lama, nilai baru), tidak bergantung pada aplikasi. Tabel audit_log hanya bisa dibaca
-- super admin dan tidak bisa diubah atau dihapus oleh pengguna mana pun lewat API.
-- Data transaksi tidak bisa dihapus permanen lewat API: SPK, vendor, kirim, bongkar, PR, mutasi, opname, riwayat harga,
-- bahan baku, dan barang jadi dibatalkan lewat status (aplikasi sudah memakai pembatalan lunak). Master (vendor,
-- customer, supplier, armada, work center) tetap bisa dihapus bila belum dipakai, tetapi penghapusannya tercatat.
-- Pembersihan oleh pemilik lewat SQL Editor (service role) tidak terpengaruh.

CREATE TABLE IF NOT EXISTS public.audit_log (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  tabel    TEXT NOT NULL,
  aksi     TEXT NOT NULL,           -- INSERT | UPDATE | DELETE
  baris_id TEXT,
  oleh     TEXT,                    -- email pengguna; 'sistem' bila bukan lewat sesi pengguna
  lama     JSONB,
  baru     JSONB
);
CREATE INDEX IF NOT EXISTS audit_log_tabel_baris ON public.audit_log (tabel, baris_id, at DESC);
CREATE INDEX IF NOT EXISTS audit_log_at ON public.audit_log (at DESC);

ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.audit_log FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.audit_log TO authenticated;
DROP POLICY IF EXISTS "audit_log_read" ON public.audit_log;
CREATE POLICY "audit_log_read" ON public.audit_log FOR SELECT TO authenticated USING (public.is_admin());
-- Tanpa kebijakan INSERT/UPDATE/DELETE dan tanpa hak tulis: hanya fungsi pemicu di bawah yang menulis.

CREATE OR REPLACE FUNCTION public.audit_row()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  o JSONB;
  n JSONB;
  rid TEXT;
BEGIN
  IF TG_OP = 'INSERT' THEN
    n := to_jsonb(NEW); rid := n ->> 'id';
  ELSIF TG_OP = 'UPDATE' THEN
    o := to_jsonb(OLD); n := to_jsonb(NEW); rid := n ->> 'id';
    IF (o - 'updated_at') = (n - 'updated_at') THEN RETURN NEW; END IF;   -- tanpa perubahan isi
  ELSE
    o := to_jsonb(OLD); rid := o ->> 'id';
  END IF;
  INSERT INTO public.audit_log (tabel, aksi, baris_id, oleh, lama, baru)
  VALUES (TG_TABLE_NAME, TG_OP, rid, COALESCE(NULLIF((SELECT auth.email()), ''), 'sistem'), o, n);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.audit_row() FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['spk','vendor','kirim','bongkar','pr','mutasi','opname','rmhist','rm','fg',
                           'mvendor','mcustomer','msupplier','marmada','mwc','muser'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_audit ON public.%I', t);
    EXECUTE format('CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.audit_row()', t);
  END LOOP;
END;
$$;

-- Larangan hapus permanen pada data transaksi: cabut kebijakan DELETE (RLS menolak semua penghapusan lewat API).
DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN SELECT policyname, tablename FROM pg_policies
           WHERE schemaname = 'public' AND cmd = 'DELETE'
             AND tablename IN ('spk','vendor','kirim','bongkar','pr','mutasi','opname','rmhist','rm','fg')
  LOOP
    EXECUTE format('DROP POLICY %I ON public.%I', r.policyname, r.tablename);
  END LOOP;
END;
$$;
